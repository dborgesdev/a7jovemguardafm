import { readFile, writeFile } from 'node:fs/promises';

// Keep the confirmed HTTP URL until HTTPS and canonical redirects are verified.
const site = JSON.parse(await readFile(new URL('../src/config/site.json', import.meta.url), 'utf8'));
const url = new URL(site.url);
if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash) {
  throw new Error('Official site URL must be HTTP(S) without credentials, query or fragment.');
}
const base = url.href;
const html = await readFile('dist/index.html', 'utf8');
if (html.includes('%SITE_URL%') || !html.includes(`rel="canonical" href="${base}"`)) {
  throw new Error('Official SEO URLs were not generated by the Vite HTML transform.');
}
await writeFile('dist/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${base}</loc></url></urlset>\n`);
await writeFile('dist/robots.txt', `User-agent: *\nAllow: /\nSitemap: ${base}sitemap.xml\n`);
